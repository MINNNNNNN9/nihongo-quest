_PART = re.compile(r"\{([^|}]+)\|([^}]+)\}|([^{]+)")
KANJI = re.compile(r"[\u4e00-\u9fff々]")


def _parse(word: str) -> tuple[str, list[tuple[str, str]]]:
    parts = [(m[1] or m[3], m[2] or "") for m in _PART.finditer(word)]
    return "".join(text for text, _ in parts), parts


_TABLE = dict(_parse(word) for word in WORDS)
_LONGEST = max(map(len, _TABLE))


def annotate(text: str) -> list[list[str]]:
    """把句子切成 [文字, 假名] 片段；不需標音的片段假名為空字串。"""
    out: list[list[str]] = []

    def push(part: str, reading: str):
        if not reading and out and not out[-1][1]:
            out[-1][0] += part
        else:
            out.append([part, reading])

    i = 0
    while i < len(text):
        for size in range(min(_LONGEST, len(text) - i), 0, -1):
            parts = _TABLE.get(text[i : i + size])
            # 「4時」不能比對到「14時」的後半
            if parts and not (text[i].isdigit() and i > 0 and text[i - 1].isdigit()):
                for part, reading in parts:
                    push(part, reading)
                i += size
                break
        else:
            push(text[i], "")
            i += 1
    return out


def uncovered(text: str) -> list[str]:
    """回傳沒有被標到假名的漢字（測試用）。"""
    return [ch for part, reading in annotate(text) if not reading for ch in KANJI.findall(part)]
